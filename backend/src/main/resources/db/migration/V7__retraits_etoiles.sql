-- Étoiles retirées par un parent (avec un motif). Les étoiles gagnées ne sont pas stockées (une par routine
-- terminée) ; un retrait est gardé à part pour que l'enfant voie ce qu'il a perdu, et peut être annulé.

create table star_penalty (
    id bigint generated by default as identity,
    member_id bigint not null,
    date_retrait date not null,
    nombre integer not null,
    motif varchar(30) not null,
    commentaire varchar(255),
    -- compte du parent qui a retiré les étoiles (conservé même si le compte disparaît)
    cree_par bigint,
    cree_le timestamp not null,
    primary key (id),
    constraint ck_star_penalty_nombre check (nombre > 0),
    constraint ck_star_penalty_motif check (motif in ('TACHE_NON_FAITE', 'MAUVAIS_COMPORTEMENT', 'DISPUTE', 'IMPOLITESSE', 'AUTRE')),
    constraint fk_star_penalty_member foreign key (member_id) references family_member (id) on delete cascade,
    constraint fk_star_penalty_account foreign key (cree_par) references user_account (id) on delete set null
);

create index idx_star_penalty_member_date on star_penalty (member_id, date_retrait);
