-- Comptes utilisateurs (pas d'inscription publique : premier compte depuis ADMIN_USERNAME / ADMIN_PASSWORD,
-- les suivants créés par un parent) et jetons « rester connecté » de Spring Security.

create table user_account (
    id bigint generated by default as identity,
    -- toujours en minuscules : l'unicité est insensible à la casse
    identifiant varchar(50) not null,
    -- null = aucun mot de passe défini (compte inactif tant qu'un parent n'en a pas défini un)
    password_hash varchar(255),
    role varchar(10) not null check (role in ('PARENT', 'ENFANT')),
    member_id bigint,
    actif boolean not null default false,
    doit_changer_mot_de_passe boolean not null default false,
    echecs_connexion integer not null default 0,
    bloque_jusqua timestamp,
    derniere_connexion timestamp,
    cree_le timestamp not null,
    -- incrémentée à chaque changement de mot de passe, désactivation ou changement de rôle : les sessions
    -- ouvertes avant sont refusées
    version_securite integer not null default 0,
    primary key (id),
    constraint uk_user_account_identifiant unique (identifiant),
    constraint ck_user_account_identifiant check (identifiant = lower(identifiant)),
    constraint fk_user_account_member foreign key (member_id) references family_member (id) on delete set null
);

-- Schéma attendu par JdbcTokenRepositoryImpl (remember-me persistant)
create table persistent_logins (
    username varchar(64) not null,
    series varchar(64) not null,
    token varchar(64) not null,
    last_used timestamp not null,
    primary key (series)
);

create index idx_persistent_logins_username on persistent_logins (username);
