-- Boutique du personnage : les étoiles s'échangent contre des pièces d'or, qui achètent des articles.
-- Le catalogue (articles et prix) est dans boutique/catalogue.json ; la base garde ce que chaque membre possède.

alter table family_settings add column etoiles_par_piece int not null default 10 check (etoiles_par_piece > 0);

-- Porter automatiquement la tenue du thème du moment (voir member_outfit)
alter table family_member add column tenue_auto boolean not null default true;

create table member_wallet (
    member_id bigint not null,
    pieces int not null default 0,
    -- étoiles déjà échangées contre des pièces (déduites du solde d'étoiles)
    etoiles_converties int not null default 0,
    version int not null default 0,
    primary key (member_id),
    constraint ck_member_wallet_pieces check (pieces >= 0),
    constraint ck_member_wallet_converties check (etoiles_converties >= 0),
    constraint fk_member_wallet_member foreign key (member_id) references family_member (id) on delete cascade
);

insert into member_wallet (member_id) select id from family_member;

create table coin_transaction (
    id bigint generated by default as identity,
    member_id bigint not null,
    type varchar(20) not null,
    -- signé : positif = pièces gagnées, négatif = dépensées
    pieces int not null,
    -- étoiles échangées (type ECHANGE)
    etoiles int,
    article_id varchar(60),
    commentaire varchar(255),
    cree_par bigint,
    cree_le timestamp not null,
    primary key (id),
    constraint ck_coin_transaction_type check (type in ('ECHANGE', 'ACHAT', 'CADEAU', 'REMBOURSEMENT', 'AJUSTEMENT')),
    constraint fk_coin_transaction_member foreign key (member_id) references family_member (id) on delete cascade
);

create index idx_coin_transaction_member on coin_transaction (member_id, id);

create table member_item (
    member_id bigint not null,
    article_id varchar(60) not null,
    acquis_le timestamp not null,
    prix_paye int not null default 0,
    primary key (member_id, article_id),
    constraint fk_member_item_member foreign key (member_id) references family_member (id) on delete cascade
);

-- Tenue enregistrée pour un thème (« ma tenue Halloween »)
create table member_outfit (
    member_id bigint not null,
    theme varchar(20) not null,
    config varchar(2000) not null,
    primary key (member_id, theme),
    constraint ck_member_outfit_theme check (theme in
        ('HALLOWEEN', 'SAINT_NICOLAS', 'NOEL', 'CARNAVAL', 'PAQUES', 'ETE', 'RENTREE', 'PRINTEMPS', 'AUTOMNE', 'HIVER', 'ANNIVERSAIRE')),
    constraint fk_member_outfit_member foreign key (member_id) references family_member (id) on delete cascade
);
